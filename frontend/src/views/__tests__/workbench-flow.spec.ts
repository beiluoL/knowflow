async function renderWorkbench(component: typeof Capture | typeof Notes | typeof NoteEdit | typeof Review | typeof StoryEdit | typeof Palace | typeof PalaceEdit, path: string) {
  const pagePath = component === PalaceEdit ? '/workbench/palace/:id' : component === NoteEdit ? '/workbench/notes/:id' : component === StoryEdit ? '/workbench/story/:id' : path.split('?')[0]
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: pagePath, component }, { path: '/:pathMatch(.*)*', component: { template: '<div />' } }] })
  await router.push(path)
  const wrapper = mount({ template: '<RouterView />' }, { global: { plugins: [createPinia(), router], stubs: { Teleport: true } } })
  await flushPromises()
  return { wrapper, router }
}
