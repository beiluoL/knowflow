-- Phase 1：AI 面试训练平台增量表。仅新增表，不改写既有会话、题库与评分快照；同一脚本可重复运行。
CREATE TABLE IF NOT EXISTS interview_generation_task (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '出题任务身份',
 user_id BIGINT NOT NULL COMMENT '服务端认证的所属用户',
 request_id VARCHAR(80) NOT NULL COMMENT '创建幂等键',
 request_hash VARCHAR(64) NOT NULL COMMENT '创建参数指纹，拒绝同键不同参数',
 category_id BIGINT NOT NULL COMMENT '知识库分类身份',
 topic VARCHAR(200) COMMENT '技术方向或主题关键词，仅作为不可信上下文',
 difficulty INT NOT NULL COMMENT '目标难度：1简单 2中等 3困难',
 question_count INT NOT NULL COMMENT '期望题数',
 status VARCHAR(20) NOT NULL COMMENT 'PENDING RUNNING SUCCESS FAILED',
 progress INT NOT NULL DEFAULT 0 COMMENT '0到100的真实生成进度',
 message VARCHAR(500) COMMENT '进度说明，不含密钥',
 error_message VARCHAR(500) COMMENT '失败原因，已脱敏',
 create_time DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL COMMENT '创建时间',
 update_time DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL COMMENT '最后状态变更时间',
 CONSTRAINT uk_igen_task UNIQUE(user_id,request_id),
 INDEX idx_igen_task_owner(user_id,id),
 INDEX idx_igen_task_status(status,update_time)
) COMMENT='RAG 面试题生成任务；内存线程池之外保留可恢复状态';

CREATE TABLE IF NOT EXISTS interview_generated_question (
 id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '生成题身份',
 task_id BIGINT NOT NULL COMMENT '来源任务身份',
 user_id BIGINT NOT NULL COMMENT '服务端所属用户',
 category_id BIGINT NOT NULL COMMENT '来源知识库分类身份',
 question_id VARCHAR(80) NOT NULL COMMENT '训练题稳定标识',
 quiz_question_id BIGINT COMMENT '发布后映射的正式题库身份',
 title VARCHAR(200) NOT NULL COMMENT '题目标题',
 category VARCHAR(120) NOT NULL COMMENT '技术分类',
 difficulty INT NOT NULL COMMENT '1简单 2中等 3困难',
 question_type VARCHAR(24) NOT NULL COMMENT '题型，当前仅 SHORT_ANSWER',
 reference_answer LONGTEXT NOT NULL COMMENT '参考答案，必须由真实检索证据支撑',
 reference_points TEXT NOT NULL COMMENT '关键考察点 JSON 数组',
 rubric TEXT NOT NULL COMMENT '评分标准 JSON',
 followups TEXT NOT NULL COMMENT '1到3条追问 JSON 数组',
 source_document_ids TEXT NOT NULL COMMENT '来源文档 ID JSON 数组',
 source_chunks LONGTEXT NOT NULL COMMENT '真实引用片段 JSON 数组，含原文摘录',
 generation_model VARCHAR(120) COMMENT '生效模型作用域标识，不含密钥',
 prompt_version VARCHAR(60) NOT NULL COMMENT '提示词版本',
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT ENABLED ARCHIVED',
 canonical_key VARCHAR(64) NOT NULL COMMENT '题目去重指纹',
 deleted INT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0有效 1删除',
 create_time DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL COMMENT '创建时间',
 update_time DATETIME DEFAULT CURRENT_TIMESTAMP NOT NULL COMMENT '最后修改时间',
 CONSTRAINT uk_igen_q UNIQUE(user_id,canonical_key),
 INDEX idx_igen_q_owner(user_id,status),
 INDEX idx_igen_q_task(task_id)
) COMMENT='知识库证据驱动的面试题干草案；不自动覆盖既有题库';
